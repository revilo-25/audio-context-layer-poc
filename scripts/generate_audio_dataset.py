"""
generate_audio_dataset.py
Synthesizes a dataset of short "soundscape" audio clips built from a fixed
vocabulary of synthetic sound-events (dog bark, car horn, footsteps, rain,
phone ring, door knock, siren, glass break, baby cry, keyboard typing).

Each clip is generated by placing 2-5 non-overlapping events at known
timestamps on a background (silence or ambient noise) within a fixed-length
window. Because every event's identity, start time, and end time are known
at generation time, we get *exact* ground truth for every question we will
later ask about the clip (what/count/temporal/causal) -- this is the key
trick that lets a small synthetic dataset be evaluated objectively.

Output:
  data/audio/clip_XXXX.wav
  data/metadata.json   (per-clip event timeline + environment label)
"""
import numpy as np
import soundfile as sf
import json
import os
import random

random.seed(42)
np.random.seed(42)

SR = 16000
CLIP_LEN = 10.0  # seconds
OUT_DIR = "/home/claude/audio_qa_poc/data"
AUDIO_DIR = os.path.join(OUT_DIR, "audio")
os.makedirs(AUDIO_DIR, exist_ok=True)

# ----------------------------------------------------------------------
# Event synthesizers: each returns a mono float32 waveform of duration `dur`
# ----------------------------------------------------------------------

def _env(n, attack=0.05, release=0.2):
    """simple attack/release amplitude envelope"""
    a = int(SR * attack)
    r = int(SR * release)
    env = np.ones(n)
    a = min(a, n // 2)
    r = min(r, n // 2)
    if a > 0:
        env[:a] = np.linspace(0, 1, a)
    if r > 0:
        env[-r:] = np.linspace(1, 0, r)
    return env

def dog_bark(dur=0.3):
    n = int(SR * dur)
    t = np.arange(n) / SR
    f0 = 400
    sig = np.sign(np.sin(2 * np.pi * f0 * t)) * np.exp(-6 * t)
    sig += 0.3 * np.random.randn(n)
    return sig * _env(n, 0.01, 0.15)

def car_horn(dur=0.6):
    n = int(SR * dur)
    t = np.arange(n) / SR
    sig = 0.6 * np.sin(2 * np.pi * 400 * t) + 0.4 * np.sin(2 * np.pi * 500 * t)
    return sig * _env(n, 0.02, 0.05)

def footsteps(dur=1.6, n_steps=4):
    n = int(SR * dur)
    sig = np.zeros(n)
    step_gap = n // n_steps
    for i in range(n_steps):
        start = i * step_gap
        click_len = int(SR * 0.05)
        click = np.random.randn(click_len) * np.linspace(1, 0, click_len) ** 2
        end = min(start + click_len, n)
        sig[start:end] += click[: end - start] * 0.8
    return sig

def rain(dur=2.0):
    n = int(SR * dur)
    sig = np.random.randn(n) * 0.15
    # low-pass-ish via simple moving average to sound less harsh
    kernel = np.ones(5) / 5
    sig = np.convolve(sig, kernel, mode="same")
    return sig * _env(n, 0.3, 0.3)

def phone_ring(dur=1.0):
    n = int(SR * dur)
    t = np.arange(n) / SR
    trill = np.sin(2 * np.pi * 1000 * t) * (np.sin(2 * np.pi * 15 * t) > 0)
    return trill.astype(float) * 0.6

def door_knock(dur=0.6, n_knocks=3):
    n = int(SR * dur)
    sig = np.zeros(n)
    gap = n // n_knocks
    for i in range(n_knocks):
        start = i * gap
        klen = int(SR * 0.04)
        t = np.arange(klen) / SR
        thump = np.sin(2 * np.pi * 120 * t) * np.exp(-40 * t)
        end = min(start + klen, n)
        sig[start:end] += thump[: end - start]
    return sig * 0.9

def siren(dur=2.5):
    n = int(SR * dur)
    t = np.arange(n) / SR
    freq = 600 + 400 * np.sin(2 * np.pi * 0.5 * t)
    phase = 2 * np.pi * np.cumsum(freq) / SR
    sig = np.sin(phase)
    return sig * _env(n, 0.3, 0.3) * 0.7

def glass_break(dur=0.4):
    n = int(SR * dur)
    sig = np.random.randn(n)
    env = np.exp(-15 * np.arange(n) / SR)
    # add a few high-frequency tonal shards
    t = np.arange(n) / SR
    for f in [2000, 3200, 4500]:
        sig += 0.3 * np.sin(2 * np.pi * f * t)
    return sig * env * 0.5

def baby_cry(dur=1.2):
    n = int(SR * dur)
    t = np.arange(n) / SR
    f0 = 500 + 150 * np.sin(2 * np.pi * 3 * t)
    sig = np.sin(2 * np.pi * f0 * t)
    return sig * _env(n, 0.1, 0.2) * 0.7

def keyboard_typing(dur=1.5, n_clicks=12):
    n = int(SR * dur)
    sig = np.zeros(n)
    for _ in range(n_clicks):
        start = random.randint(0, n - int(SR * 0.02) - 1)
        klen = int(SR * 0.015)
        click = np.random.randn(klen) * np.linspace(1, 0, klen)
        end = min(start + klen, n)
        sig[start:end] += click[: end - start] * 0.5
    return sig

EVENTS = {
    "dog_bark": dog_bark,
    "car_horn": car_horn,
    "footsteps": footsteps,
    "rain": rain,
    "phone_ring": phone_ring,
    "door_knock": door_knock,
    "siren": siren,
    "glass_break": glass_break,
    "baby_cry": baby_cry,
    "keyboard_typing": keyboard_typing,
}

DEFAULT_DUR = {
    "dog_bark": 0.3, "car_horn": 0.6, "footsteps": 1.6, "rain": 2.0,
    "phone_ring": 1.0, "door_knock": 0.6, "siren": 2.5, "glass_break": 0.4,
    "baby_cry": 1.2, "keyboard_typing": 1.5,
}

# Environment inference table: which event combos suggest which scene.
# Used both to LABEL clips (weak supervision for "what environment" Qs)
# and to generate CAUSAL ("why") question templates.
ENVIRONMENT_RULES = [
    ({"dog_bark", "footsteps", "car_horn"}, "street / outdoor urban scene"),
    ({"rain", "footsteps"}, "outdoors in the rain"),
    ({"phone_ring", "keyboard_typing"}, "office / indoor workspace"),
    ({"baby_cry", "door_knock"}, "home / domestic indoor scene"),
    ({"siren", "car_horn"}, "street with emergency vehicle traffic"),
    ({"glass_break", "dog_bark"}, "home intrusion / disturbance scene"),
]

def infer_environment(event_set):
    best, best_score = "ambiguous / mixed scene", 0
    for rule_set, label in ENVIRONMENT_RULES:
        overlap = len(rule_set & event_set)
        if overlap > best_score:
            best_score = overlap
            best = label
    return best

CAUSES = {
    "dog_bark": "a dog reacting to a nearby stimulus (person, animal, or noise)",
    "car_horn": "a driver signaling another vehicle or pedestrian",
    "footsteps": "a person walking through or near the scene",
    "rain": "precipitation falling in the recorded environment",
    "phone_ring": "an incoming call on a nearby phone",
    "door_knock": "someone requesting entry at a door",
    "siren": "an emergency vehicle passing through the area",
    "glass_break": "an object breaking a glass surface, e.g. a window",
    "baby_cry": "an infant expressing distress or need",
    "keyboard_typing": "someone typing on a computer keyboard",
}

def make_clip(clip_id, n_events):
    n_samples = int(SR * CLIP_LEN)
    audio = np.zeros(n_samples)
    chosen = random.sample(list(EVENTS.keys()), k=n_events)
    timeline = []
    cursor = 0.0
    # place events with random gaps, ensure they fit and stay non-overlapping
    remaining_budget = CLIP_LEN - sum(DEFAULT_DUR[e] for e in chosen)
    if remaining_budget < 0:
        chosen = chosen[:3]
        remaining_budget = CLIP_LEN - sum(DEFAULT_DUR[e] for e in chosen)
    gaps = np.random.dirichlet(np.ones(len(chosen) + 1)) * max(remaining_budget, 0.5)
    for i, ev in enumerate(chosen):
        cursor += gaps[i]
        dur = DEFAULT_DUR[ev]
        wav = EVENTS[ev](dur)
        start_sample = int(cursor * SR)
        end_sample = min(start_sample + len(wav), n_samples)
        audio[start_sample:end_sample] += wav[: end_sample - start_sample]
        timeline.append({
            "event": ev,
            "start": round(cursor, 3),
            "end": round(cursor + dur, 3),
        })
        cursor += dur
    # light background hiss so clips aren't pure digital silence
    audio += np.random.randn(n_samples) * 0.01
    # normalize
    peak = np.max(np.abs(audio)) + 1e-9
    audio = audio / peak * 0.9
    timeline.sort(key=lambda x: x["start"])
    event_set = set([t["event"] for t in timeline])
    env_label = infer_environment(event_set)
    fname = f"clip_{clip_id:04d}.wav"
    sf.write(os.path.join(AUDIO_DIR, fname), audio.astype(np.float32), SR)
    return {
        "clip_id": f"clip_{clip_id:04d}",
        "file": fname,
        "duration": CLIP_LEN,
        "timeline": timeline,
        "environment": env_label,
    }

def main(n_clips=220):
    metadata = []
    for i in range(n_clips):
        n_events = random.choice([2, 3, 3, 4, 4, 5])  # skew toward 3-4 events
        metadata.append(make_clip(i, n_events))
    with open(os.path.join(OUT_DIR, "metadata.json"), "w") as f:
        json.dump(metadata, f, indent=2)
    print(f"Generated {len(metadata)} clips -> {AUDIO_DIR}")
    # quick vocab stats
    from collections import Counter
    c = Counter(ev["event"] for m in metadata for ev in m["timeline"])
    print("Event frequency:", dict(c))

if __name__ == "__main__":
    main()
